"""Problem 2: estimate the handbook's token count and per-call cost.

Usage: python scripts/estimate_handbook.py  -> writes output/handbook_estimate.md
"""
import json
from pathlib import Path

import tiktoken

ROOT = Path(__file__).resolve().parent.parent
HANDBOOK = ROOT / "data" / "shop_handbook.md"
PRICES = ROOT / "data" / "prices.json"
OUT = ROOT / "output" / "handbook_estimate.md"
MODEL_KEY = "gpt-6-luna"
ENCODING = "o200k_base"  # tokenizer used by current OpenAI GPT models
CALLS = 1000

text = HANDBOOK.read_text(encoding="utf-8")
tokens = len(tiktoken.get_encoding(ENCODING).encode(text))
p = json.loads(PRICES.read_text())[MODEL_KEY]
M = 1_000_000


def usd(rate):
    return tokens * rate / M


in_cost = usd(p["input_per_1m"])
write_cost = usd(p["cache_write_per_1m"])
hit_cost = usd(p["cached_input_per_1m"])
no_cache_total = CALLS * in_cost
cache_total = write_cost + (CALLS - 1) * hit_cost
saving = 1 - cache_total / no_cache_total

md = f"""# Problem 2: Handbook size and cost estimates

The vendor desk agent sends `data/shop_handbook.md` to the model on every call, so we estimate what the handbook alone costs.
Generated by `scripts/estimate_handbook.py`. Prices are from `data/prices.json` (`{MODEL_KEY}`).

## Token count

| Measure | Value |
|---|---|
| Characters | {len(text):,} |
| Words | {len(text.split()):,} |
| **Tokens (tiktoken `{ENCODING}`)** | **{tokens:,}** |

That's about {len(text)/tokens:.2f} characters per token, close to the usual ~4-character rule of thumb ({len(text)/4:,.0f} tokens by that rule).
This counts the handbook text only. The API also counts message wrappers, the system prompt, the vendor document and the output, so real runs will show more input tokens.

## Prices (per 1M tokens)

| Rate | $ / 1M tokens |
|---|---|
| Input (uncached) | ${p['input_per_1m']} |
| Cache write | ${p['cache_write_per_1m']} |
| Cached input (cache hit) | ${p['cached_input_per_1m']} |
| Output | ${p['output_per_1m']} (not used here: the handbook is input only) |

## Cost of the handbook alone

Cost = tokens x rate / 1,000,000.

**One call, without caching:**
{tokens:,} x ${p['input_per_1m']} / 1,000,000 = **${in_cost:.7f}** (about {in_cost*100:.3f} cents)

**One call, with caching:**
- First call writes the cache: {tokens:,} x ${p['cache_write_per_1m']} / 1,000,000 = **${write_cost:.7f}**
- Each later call reads the cache: {tokens:,} x ${p['cached_input_per_1m']} / 1,000,000 = **${hit_cost:.7f}**

**{CALLS:,} calls, without caching:**
{CALLS:,} x ${in_cost:.7f} = **${no_cache_total:.4f}**

**{CALLS:,} calls, with caching** (1 cache write + {CALLS-1:,} cache hits):
${write_cost:.7f} + {CALLS-1:,} x ${hit_cost:.7f} = ${write_cost:.7f} + ${(CALLS-1)*hit_cost:.7f} = **${cache_total:.4f}**

## Summary

| Scenario | 1 call | {CALLS:,} calls |
|---|---|---|
| No caching | ${in_cost:.7f} | ${no_cache_total:.4f} |
| With caching | ${write_cost:.7f} (write) / ${hit_cost:.7f} (hit) | ${cache_total:.4f} |

Caching cuts the handbook cost of {CALLS:,} calls by about **{saving:.1%}**. The first call costs 25% more than uncached because of the cache write, and every call after that costs one-tenth as much.

## Assumptions to check in Problem 4

- The handbook is a fixed prefix at the start of every prompt, so it can be cached.
- The cache stays warm between calls, so there is only one cache write in {CALLS:,} calls. If the cache expires, each re-write adds another ${write_cost:.7f}.
- The `{ENCODING}` count matches the model's own tokenizer. We'll compare it to the `usage` token counts from real runs.

**Checked in Problem 4:** see `output/cache_test.md`, "Real numbers vs. the Problem 2 estimates". The token count and cache-read price held up, but each document takes 2 model calls and about 21,500 input tokens, so the real bill per document is about twice this estimate.
"""
OUT.write_text(md, encoding="utf-8")
print(md)
